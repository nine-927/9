/* =====================================================================
 *  俄罗斯方块 · 第 1 步:把方块"画"出来
 * ---------------------------------------------------------------------
 *  核心思想:
 *    每一个方块形状,本质就是一个二维数组。
 *    数组里 1 表示"这一格有方块",0 表示"这一格是空的"。
 *    把数组从头到尾遍历一遍,该画的地方画,不该画的地方留空,
 *    形状自然就出现在屏幕上了。
 *
 *  编译:  cl step1_shape.c      (VS 开发者命令行)
 *  运行:  step1_shape.exe
 * ===================================================================== */
#include <stdio.h>

int main(void)
{
    /* 一个 T 形方块:第一行三格全满,第二行只有中间一格 */
    int shape[2][3] = {
        { 1, 1, 1 },
        { 0, 1, 0 }
    };

    int row, col;

    /* 外层循环走"行",内层循环走"列" —— 这就是遍历二维数组 */
    for (row = 0; row < 2; row++) {
        for (col = 0; col < 3; col++) {
            if (shape[row][col] == 1) {
                printf("[]");       /* 有方块:画两个字符 */
            } else {
                printf("  ");       /* 空的:画两个空格,保持宽度一致 */
            }
        }
        printf("\n");               /* 一行画完,换行 */
    }

    return 0;
}
